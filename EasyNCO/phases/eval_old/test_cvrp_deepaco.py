import hydra
import os
import sys
import torch
from omegaconf import DictConfig

current_dir = os.path.dirname(os.path.abspath(__file__))
split_path = current_dir.split("/")
root_dir = "/".join(split_path[:-2])
insert_dir = "/".join(split_path[:-3])
sys.path.insert(0, insert_dir)

from EasyNCO.data import *
from EasyNCO.phases.train.rl import REINFORCENARLightning
from EasyNCO.utils.utils import set_device, seed_everything

seed = 2024
gpu_device = 0

device = set_device(use_cuda=True,
                    gpu_device=gpu_device)
seed_everything(seed=seed)

current_dir = os.path.dirname(os.path.abspath(__file__))
split_path = current_dir.split("/")
root_dir = "/".join(split_path[:-2])
insert_dir = "/".join(split_path[:-5])
sys.path.insert(0, insert_dir)
config_path = f"{root_dir}/configs"

@hydra.main(config_path = config_path, config_name = 'cvrp_deepaco_config.yaml')
def main(cfg : DictConfig):
    model_path = f"{cfg.test_loader.model_dirpath}{cfg.test_loader.model_filename}"
    absolute_path = f"{root_dir}{model_path}"
    tester = hydra.utils.instantiate(cfg.trainer, devices=[gpu_device], )
    policy = hydra.utils.instantiate(cfg.model)

    file_type = os.path.splitext(absolute_path)[-1]

    if file_type == '.pt':
        # This code is used to load the model, which is a 'pt' file generated by pytorch.
        state_dict = torch.load(absolute_path, map_location=torch.device(device))
        policy.load_state_dict(state_dict)
        model = REINFORCENARLightning(problem_type = cfg.test_loader.problem_type,
                                      problem_size = cfg.test_loader.problem_size,
                                      policy = policy,
                                      policy_param = cfg.test_loader.test_params['policy_param'],
                                      batch_size = cfg.test_loader.test_params['test_batch_size'],
                                      episodes = cfg.test_loader.test_params['test_episodes'],
                                      iteration = cfg.test_loader.iteration,
                                      )
    elif file_type == '.ckpt':
        # This code is used to load the model, which is a 'ckpt' file generated by pytorch lightning.
        model = REINFORCENARLightning.load_from_checkpoint(absolute_path,
                                                           env_name = cfg.test_loader.env_name,
                                                           problem_size = cfg.test_loader.problem_size,
                                                           policy = policy,
                                                           policy_param = cfg.test_loader.test_params['policy_param'],
                                                           batch_size = cfg.test_loader.test_params['test_batch_size'],
                                                           episodes = cfg.test_loader.test_params['test_episodes'],
                                                           iteration = cfg.test_loader.iteration,
                                                           )
    else:
        raise NotImplementedError(f"The file type ({file_type}) is not supported in current version")

    data_dict = cfg.test_loader.data_dict
    if data_dict['use_customized_data']:
        path = data_dict['data_path']
        data_path = f"{root_dir}{path}"
    else:
        data_path = None

    data_loader = test_DataLoader(cfg.test_loader.problem_type,
                                      {
                                          'data_size': cfg.test_loader.test_params["test_episodes"],
                                          'problem_size': cfg.test_loader.problem_size,
                                          'batch_size': cfg.test_loader.test_params["test_batch_size"],
                                          'device' : device,
                                          'path' : data_path,
                                      })

    tester.test(model, dataloaders = data_loader)


def test_DataLoader(env_name: str, config: dict):
    dataloader = {
        'tsp': TSPGenerator,
        'cvrp': CVRPGenerator,
        'op': OPGenerator,
        'pctsp': PCTSPGenerator,
        'sop': SOPGenerator,
        'smtwtp': SMTWTPGenerator,
        'rcpsp': RCPSPGenerator,
        'mkp': MKPGenerator,
        'bpp': BPPGenerator,
    }

    return dataloader[env_name](**config)


if __name__ == '__main__':
    main()