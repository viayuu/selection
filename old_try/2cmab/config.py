"""
config.py — Online Neural-LinUCB 所有可调参数集中配置

修改此文件中的默认值即可调整实验参数, 无需在命令行传参。
命令行参数会覆盖此处的默认值。
"""


# ============================================================
#  数据参数
# ============================================================

# 每种问题类型 (TSP/CVRP) 取多少实例, 0 表示全部
# 全部: TSP 10000 + CVRP 10000 = 20000 条
# 快速调试建议设 500~1000
N_INSTANCES = 0

# 随机种子 (影响数据划分、训练顺序等)
SEED = 42

# 计算设备: "cpu" 或 "cuda"
DEVICE = "cuda"


# ============================================================
#  LinUCB / Neural-LinUCB 共享参数
# ============================================================

# UCB 探索系数 α, 越大越倾向探索未知臂, 越小越倾向利用已知最优
# 论文典型值: 0.1 ~ 2.0
ALPHA = 1.0


# ============================================================
#  Neural-LinUCB 网络参数
# ============================================================

# φ 维度: encoder 输出经过 context_proj 后的特征维度
# 更大的维度表达力更强, 但 LinUCB 的 Z 矩阵是 phi_dim × phi_dim, 开销随之增大
PHI_DIM = 64

# LinUCB 正则化系数 λ, Z 矩阵初始化为 λI
# 越大越保守 (所有臂初始不确定性更均匀)
REG = 1.0

# Encoder 学习率 (较小, 防止大 encoder 在少量数据上过拟合)
LR_ENCODER = 1e-4

# context_proj + reward_heads 学习率
LR_HEAD = 1e-3


# ============================================================
#  在线训练调度参数
# ============================================================

# 每隔多少步在线交互后, 触发一次网络重训 (论文中的 q)
# 越小: 网络更新越频繁, 特征适应更快, 但每次重训有开销
# 越大: 更新少, 省时间, 但特征可能滞后
TRAIN_EVERY = 50

# 每次网络重训的 epoch 数 (论文中的 J)
# 遍历训练历史 J 遍, 每遍做 n_train/batch_size 次梯度更新
TRAIN_STEPS = 10

# 梯度累积的 mini-batch 大小
# 因为 TSP/CVRP 输入维度不同, 无法真正拼 batch, 所以用梯度累积等价实现
# 越大: 梯度更稳定, optimizer.step() 次数越少, 训练更快
BATCH_SIZE = 64

# 训练用历史记录上限 (滑动窗口)
# 网络训练时只用最近 H 条历史, 防止 t 增大后重训变慢
# rebuild 统计量仍然使用全部历史 (只做前向传播, 较快)
# 0 表示不限制
MAX_HISTORY = 5000


# ============================================================
#  日志参数
# ============================================================

# 日志输出目录 (相对于 2cmab/ 目录)
LOG_DIR = "logs"

# 是否在终端也输出详细日志 (每次选臂的分数等)
# False: 详细日志只写文件, 终端只显示 checkpoint 摘要
# True: 终端也输出全部日志 (调试用, 输出量很大)
VERBOSE = True


# ============================================================
#  Checkpoint 参数
# ============================================================

# 是否保存训练完成后的模型 checkpoint
SAVE_CHECKPOINT = True

# checkpoint 保存目录 (相对于 2cmab/ 目录)
CHECKPOINT_DIR = "checkpoints"

# 每隔多少轮在线交互保存一次 checkpoint (0=只在训练结束时保存)
# 建议设为 TRAIN_EVERY 的整数倍, 这样每次保存时网络刚刚重训过
CHECKPOINT_EVERY = 500
