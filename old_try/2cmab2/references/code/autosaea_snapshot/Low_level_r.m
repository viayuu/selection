% =========================================================================
% Low_level_r: 低层奖励计算函数
% 对应论文 Algorithm 3 第7行, 以及论文公式(24)
%
% 核心思想: 新生成的解 x_t 在当前种群P中的排名越好, 奖励越高
% 奖励设计的优点:
%   1) 有界: r ∈ [0, 1]
%   2) 与排名线性相关: 排名越好, 奖励越大
%   3) 非稀疏: 即使新解不是最优, 也能获得正奖励(只要不是最差)
%   4) 相对稳定: 基于排名而非绝对适应度值, 不受函数值量级变化影响
%
% 输入:
%   ghf           - 当前种群P的适应度值向量 (1×N)
%   hf            - 全部历史数据库的适应度值(用于判断是否为全局最优)
%   candidate_fit - 新生成解 x_t 的真实适应度值 f(x_t)
%   NFEs          - 当前函数评估次数(用于日志输出)
%   Arm           - 当前使用的摇臂名称字符串(用于日志输出)
%
% 输出:
%   reward - 低层奖励 r_{a_t^L}, 范围 [0, 1]
%
% 论文公式(24):
%   r_{a_t^L} = -1/N · I(x_t) + (N+1)/N
%
% 其中:
%   N = 种群大小
%   I(x_t) = x_t 在种群P中的排名(1=最好, N+1=比所有都差)
%
% 排名与奖励的对应关系(N=100为例):
%   I(x_t) = 1   (最好) → r = -1/100·1 + 101/100 = 1.00
%   I(x_t) = 50  (中等) → r = -1/100·50 + 101/100 = 0.51
%   I(x_t) = 101 (最差) → r = -1/100·101 + 101/100 = 0.00
% =========================================================================
function [reward] = Low_level_r(ghf, hf, candidate_fit, NFEs, Arm)
         N = length(ghf);                   % N: 当前种群大小 (论文中的N)
         ghf = reshape(ghf, 1, N);          % 确保 ghf 是行向量 (1×N)
         ghf_sum = [ghf, candidate_fit];    % 将新解的适应度值追加到种群适应度末尾
                                            % 现在 ghf_sum 有 N+1 个元素
         [~, index] = sort(ghf_sum);        % 对N+1个值升序排序, index是排序后的原始索引
         in = find(index == (N+1));         % 找到新解(第N+1个元素)在排序后的位置
                                            % in 就是 I(x_t), 即新解的排名
         % --- 计算低层奖励, 对应论文公式(24) ---
         % reward = -1/N * I(x_t) + (N+1)/N
         reward = -1/N*in + (N+1)/N;

         % 如果新解是全局最优(整个历史数据库中最好的), 打印提示信息
         if candidate_fit == min(hf)
            disp(['Current optimal obtained by ' Arm 'arm is: ' num2str(candidate_fit) ' NFE=' num2str(NFEs)]);
         end

end
